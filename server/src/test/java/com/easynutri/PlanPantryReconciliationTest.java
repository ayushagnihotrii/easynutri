package com.easynutri;

import static org.junit.jupiter.api.Assertions.*;

import com.easynutri.dto.AddPantryItemRequest;
import com.easynutri.dto.GroceryItemDto;
import com.easynutri.entity.FoodEntity;
import com.easynutri.entity.MealPlanItemEntity;
import com.easynutri.entity.RecipeEntity;
import com.easynutri.entity.RecipeIngredientEntity;
import com.easynutri.entity.UserEntity;
import com.easynutri.repository.FoodRepository;
import com.easynutri.repository.MealPlanItemRepository;
import com.easynutri.repository.PantryItemRepository;
import com.easynutri.repository.RecipeRepository;
import com.easynutri.repository.UserRepository;
import com.easynutri.service.GroceryService;
import com.easynutri.service.PantryService;
import java.time.LocalDate;
import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.annotation.Transactional;

@SpringBootTest
@ActiveProfiles("dev")
@Transactional
class PlanPantryReconciliationTest {

  @Autowired private GroceryService groceryService;
  @Autowired private PantryService pantryService;
  @Autowired private UserRepository userRepository;
  @Autowired private RecipeRepository recipeRepository;
  @Autowired private FoodRepository foodRepository;
  @Autowired private MealPlanItemRepository mealPlanItemRepository;
  @Autowired private PantryItemRepository pantryItemRepository;

  private FoodEntity sampleFood;
  private RecipeEntity sampleRecipe;

  @BeforeEach
  void setUp() {
    List<FoodEntity> foods = foodRepository.findAll();
    if (!foods.isEmpty()) {
      sampleFood = foods.get(0);
    } else {
      sampleFood =
          foodRepository.save(
              new FoodEntity(
                  "food_spinach_test2",
                  "Spinach Test",
                  "पालक",
                  "VEGETABLES",
                  23.0,
                  2.9,
                  3.6,
                  0.4,
                  "IFCT",
                  true));
    }

    List<RecipeEntity> recipes = recipeRepository.findAll();
    if (!recipes.isEmpty()) {
      sampleRecipe = recipes.get(0);
    } else {
      RecipeEntity r =
          new RecipeEntity(
              "recipe_test_khichdi",
              "Test Khichdi",
              "खिचड़ी",
              "Healthy khichdi",
              2,
              10,
              20,
              "DINNER",
              "MAIN");
      r.getIngredients().add(new RecipeIngredientEntity(r, sampleFood, 150.0, false));
      sampleRecipe = recipeRepository.save(r);
    }
  }

  @Test
  @DisplayName("Reconcile with meal plan subtracts pantry inventory from recipe demands")
  void testPlanToPantryReconciliation() {
    UserEntity demo = userRepository.findByUsername("demo").orElseThrow();
    Long userId = demo.getId();

    LocalDate start = LocalDate.now();
    LocalDate end = start.plusDays(6);

    // Clear previous pantry items to test precise reconciliation deficit
    pantryItemRepository.deleteByUserId(userId);

    // Schedule recipe for tomorrow
    mealPlanItemRepository.save(
        new MealPlanItemEntity(demo, sampleRecipe, start.plusDays(1), "DINNER", 2));

    // Place partial stock in pantry for first ingredient
    FoodEntity firstIng =
        sampleRecipe.getIngredients().isEmpty()
            ? sampleFood
            : sampleRecipe.getIngredients().get(0).getFood();

    pantryService.addPantryItem(
        userId,
        new AddPantryItemRequest(
            firstIng.getId(),
            10.0,
            "g",
            "CUPBOARD",
            LocalDate.now().plusDays(10),
            LocalDate.now(),
            ""));

    // Reconcile
    int generatedCount = groceryService.reconcileWithWeeklyPlan(userId, start, end);
    assertTrue(
        generatedCount > 0, "Should generate grocery items for ingredients needing purchase");

    List<GroceryItemDto> list = groceryService.getGroceryItems(userId);
    assertTrue(list.stream().anyMatch(GroceryItemDto::isAutoGenerated));
  }

  @Test
  @DisplayName("Transfer purchased grocery item directly to pantry inventory")
  void testTransferToPantry() {
    UserEntity demo = userRepository.findByUsername("demo").orElseThrow();
    Long userId = demo.getId();

    // Add grocery item
    com.easynutri.dto.AddGroceryItemRequest req =
        new com.easynutri.dto.AddGroceryItemRequest(
            sampleFood.getNameEn(), 300.0, "g", "VEGETABLES", sampleFood.getId());
    GroceryItemDto item = groceryService.addItem(userId, req);

    // Transfer to pantry
    groceryService.transferToPantry(userId, item.id(), LocalDate.now().plusDays(7), "REFRIGERATED");

    var pantry = pantryService.getUserPantry(userId);
    assertTrue(pantry.stream().anyMatch(p -> p.foodId().equals(sampleFood.getId())));
  }
}
