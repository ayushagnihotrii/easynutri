package com.easynutri.dto;

public record GroceryItemDto(
    Long id,
    String itemName,
    double quantity,
    String unit,
    boolean checked,
    String category,
    String foodId,
    boolean isAutoGenerated) {

  public GroceryItemDto(
      Long id,
      String itemName,
      double quantity,
      String unit,
      boolean checked,
      String category,
      String foodId) {
    this(id, itemName, quantity, unit, checked, category, foodId, false);
  }
}
