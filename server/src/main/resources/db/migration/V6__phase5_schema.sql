-- EasyNutri Phase 5 Relational Schema Migration: AI Assistant Conversations, Tool Executions, Recipe Adaptations, and Weekly Insights

-- 1. AI Chat Conversations
CREATE TABLE ai_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL DEFAULT 'Nutrition Consultation',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_conversations_user ON ai_conversations(user_id);

-- 2. AI Messages with Tool & Safety Metadata
CREATE TABLE ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
    role VARCHAR(30) NOT NULL,
    content TEXT NOT NULL,
    executed_tools TEXT,
    safety_verdict VARCHAR(30) NOT NULL DEFAULT 'ALLOW',
    safety_notes TEXT,
    is_deterministic BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_messages_conversation ON ai_messages(conversation_id);

-- 3. AI Tool Executions Audit Log
CREATE TABLE ai_tool_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT REFERENCES ai_messages(id) ON DELETE CASCADE,
    tool_name VARCHAR(100) NOT NULL,
    arguments_json TEXT,
    result_json TEXT,
    execution_duration_ms BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_tool_executions_message ON ai_tool_executions(message_id);

-- 4. User Saved Recipe Adaptations & Variants
CREATE TABLE recipe_adaptations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    base_recipe_id VARCHAR(100) NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    adaptation_title VARCHAR(200) NOT NULL,
    adaptation_type VARCHAR(50) NOT NULL DEFAULT 'CUSTOM',
    modifications_json TEXT NOT NULL,
    instructions_text TEXT,
    calories_per_serving DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    protein_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    carbs_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    fat_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    fiber_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    sodium_mg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    safety_verdict VARCHAR(30) NOT NULL DEFAULT 'ALLOW',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_recipe_adaptations_user ON recipe_adaptations(user_id);

-- 5. Stored Weekly Check-ins & Supported Insights
CREATE TABLE weekly_insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    week_start_date DATE NOT NULL,
    category VARCHAR(50) NOT NULL,
    observation_text TEXT NOT NULL,
    suggested_action_type VARCHAR(50),
    suggested_action_payload VARCHAR(255),
    is_positive BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_weekly_insights_user_date ON weekly_insights(user_id, week_start_date);
