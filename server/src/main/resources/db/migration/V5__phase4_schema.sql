-- EasyNutri Phase 4 Schema Migration: Food Diary, Activity & Steps, Hydration, Weight & Progress Tracking

-- 1. Food Diary Daily Meal Slots (Breakfast, Lunch, Dinner, Snack)
CREATE TABLE food_diary_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    diary_date DATE NOT NULL,
    meal_slot VARCHAR(30) NOT NULL,
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_diary_user_date_slot UNIQUE (user_id, diary_date, meal_slot)
);

CREATE INDEX idx_diary_entries_user_date ON food_diary_entries(user_id, diary_date);

-- 2. Food Diary Items with Immutable Nutritional Snapshots
CREATE TABLE food_diary_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES food_diary_entries(id) ON DELETE CASCADE,
    food_id VARCHAR(100),
    recipe_id VARCHAR(100),
    item_name VARCHAR(255) NOT NULL,
    amount_g DOUBLE PRECISION NOT NULL DEFAULT 100.0,
    servings DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    calories DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    protein_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    carbs_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    fat_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    fiber_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    sodium_mg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_diary_items_entry ON food_diary_items(entry_id);

-- 3. Daily Step Tracking Records
CREATE TABLE step_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    record_date DATE NOT NULL,
    step_count INT NOT NULL DEFAULT 0,
    goal_steps INT NOT NULL DEFAULT 10000,
    source_type VARCHAR(50) NOT NULL DEFAULT 'MANUAL',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_step_user_date UNIQUE (user_id, record_date)
);

CREATE INDEX idx_step_records_user_date ON step_records(user_id, record_date);

-- 4. Workouts & Physical Activity Logs
CREATE TABLE workout_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    record_date DATE NOT NULL,
    activity_type VARCHAR(50) NOT NULL,
    intensity VARCHAR(30) NOT NULL DEFAULT 'MODERATE',
    duration_minutes INT NOT NULL,
    distance_km DOUBLE PRECISION,
    calories_burned DOUBLE PRECISION NOT NULL,
    met_value DOUBLE PRECISION NOT NULL,
    notes TEXT,
    source_type VARCHAR(50) NOT NULL DEFAULT 'MANUAL',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_workout_logs_user_date ON workout_logs(user_id, record_date);

-- 5. Water Hydration Logs
CREATE TABLE water_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    record_date DATE NOT NULL,
    amount_ml INT NOT NULL,
    notes VARCHAR(255),
    logged_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_water_logs_user_date ON water_logs(user_id, record_date);

-- 6. Weight Measurements & BMI Progress
CREATE TABLE weight_measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    measurement_date DATE NOT NULL,
    weight_kg DOUBLE PRECISION NOT NULL,
    bmi DOUBLE PRECISION,
    notes VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_weight_measurements_user_date ON weight_measurements(user_id, measurement_date);

-- 7. Hydration Target & Notification Preferences
CREATE TABLE hydration_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    daily_target_ml INT NOT NULL DEFAULT 2500,
    clinical_restriction BOOLEAN NOT NULL DEFAULT FALSE,
    clinical_notes VARCHAR(255),
    reminder_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    reminder_interval_hours INT NOT NULL DEFAULT 2,
    start_time VARCHAR(10) NOT NULL DEFAULT '08:00',
    end_time VARCHAR(10) NOT NULL DEFAULT '22:00',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
