-- EasyNutri Phase 1 Relational Schema Migration

CREATE TABLE user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    age INT NOT NULL,
    biological_sex VARCHAR(20) NOT NULL,
    height_cm DOUBLE PRECISION NOT NULL,
    weight_kg DOUBLE PRECISION NOT NULL,
    activity_level VARCHAR(30) NOT NULL DEFAULT 'MODERATE',
    health_goal VARCHAR(30) NOT NULL DEFAULT 'MAINTAIN',
    dietary_preference VARCHAR(30) NOT NULL DEFAULT 'VEGETARIAN',
    is_pregnant BOOLEAN NOT NULL DEFAULT FALSE,
    sensitive_mode BOOLEAN NOT NULL DEFAULT FALSE,
    onboarding_completed BOOLEAN NOT NULL DEFAULT FALSE,
    target_calories INT,
    target_protein_g INT,
    target_carb_g INT,
    target_fat_g INT,
    target_water_l DOUBLE PRECISION,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_allergies (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    allergy VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, allergy)
);

CREATE TABLE user_health_conditions (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    health_condition VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, health_condition)
);

CREATE TABLE foods (
    id VARCHAR(100) PRIMARY KEY,
    name_en VARCHAR(200) NOT NULL,
    name_hi VARCHAR(200),
    category VARCHAR(50) NOT NULL,
    energy_kcal DOUBLE PRECISION NOT NULL,
    protein_g DOUBLE PRECISION NOT NULL,
    carbohydrate_g DOUBLE PRECISION NOT NULL,
    sugar_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    fat_g DOUBLE PRECISION NOT NULL,
    saturated_fat_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    fibre_g DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    sodium_mg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    potassium_mg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    calcium_mg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    iron_mg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    allergen_tags VARCHAR(500),
    diet_flags VARCHAR(500),
    source VARCHAR(50) NOT NULL DEFAULT 'SAMPLE',
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_foods_name_en ON foods(name_en);
CREATE INDEX idx_foods_category ON foods(category);

CREATE TABLE recipes (
    id VARCHAR(100) PRIMARY KEY,
    title_en VARCHAR(200) NOT NULL,
    title_hi VARCHAR(200),
    description_en TEXT,
    base_servings INT NOT NULL DEFAULT 2,
    prep_minutes INT NOT NULL DEFAULT 15,
    cook_minutes INT NOT NULL DEFAULT 20,
    meal_slot VARCHAR(30) NOT NULL,
    meal_role VARCHAR(30) NOT NULL DEFAULT 'MAIN',
    instructions_text TEXT,
    tags VARCHAR(500),
    source VARCHAR(50) NOT NULL DEFAULT 'SAMPLE',
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_recipes_meal_slot ON recipes(meal_slot);

CREATE TABLE recipe_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id VARCHAR(100) NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    food_id VARCHAR(100) NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    amount_g DOUBLE PRECISION NOT NULL,
    optional BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE pantry_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    food_id VARCHAR(100) NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    quantity_g DOUBLE PRECISION NOT NULL,
    expiration_date DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pantry_user ON pantry_items(user_id);
