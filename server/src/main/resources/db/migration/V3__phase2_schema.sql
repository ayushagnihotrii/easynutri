-- EasyNutri Phase 2 Relational Schema Migration: Grocery, Meal Plan, Saved Recipes, Food Portions

CREATE TABLE saved_recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipe_id VARCHAR(100) NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_saved_recipe UNIQUE (user_id, recipe_id)
);

CREATE INDEX idx_saved_recipes_user ON saved_recipes(user_id);

CREATE TABLE grocery_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    food_id VARCHAR(100) REFERENCES foods(id) ON DELETE SET NULL,
    item_name VARCHAR(200) NOT NULL,
    quantity DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    unit VARCHAR(50) NOT NULL DEFAULT 'serving',
    checked BOOLEAN NOT NULL DEFAULT FALSE,
    category VARCHAR(50) NOT NULL DEFAULT 'GENERAL',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_grocery_items_user ON grocery_items(user_id);

CREATE TABLE meal_plan_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipe_id VARCHAR(100) NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    planned_date DATE NOT NULL,
    meal_slot VARCHAR(30) NOT NULL DEFAULT 'LUNCH',
    servings INT NOT NULL DEFAULT 2,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_meal_plan_user_date ON meal_plan_items(user_id, planned_date);

CREATE TABLE food_portions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_id VARCHAR(100) NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    portion_name VARCHAR(100) NOT NULL,
    grams DOUBLE PRECISION NOT NULL
);

CREATE INDEX idx_portions_food ON food_portions(food_id);
