-- EasyNutri Phase 3 Relational Schema Migration: Weekly Planner, Collections, Cooking Sessions, Notifications

-- 1. Extend meal_plan_items with locked state, completion tracking, selection rationale, and notes
ALTER TABLE meal_plan_items ADD COLUMN locked BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE meal_plan_items ADD COLUMN completed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE meal_plan_items ADD COLUMN selection_reason VARCHAR(255);
ALTER TABLE meal_plan_items ADD COLUMN notes TEXT;

-- 2. Extend pantry_items with storage location, unit, purchase date, and notes
ALTER TABLE pantry_items ADD COLUMN storage_location VARCHAR(30) NOT NULL DEFAULT 'CUPBOARD';
ALTER TABLE pantry_items ADD COLUMN unit VARCHAR(30) NOT NULL DEFAULT 'g';
ALTER TABLE pantry_items ADD COLUMN purchase_date DATE;
ALTER TABLE pantry_items ADD COLUMN notes TEXT;

-- 3. Extend grocery_items with auto-generation tracking to protect manual additions during regeneration
ALTER TABLE grocery_items ADD COLUMN is_auto_generated BOOLEAN NOT NULL DEFAULT FALSE;

-- 4. User Recipe Collections (Favorites, High Protein, Jain, Diabetic-Friendly, etc.)
CREATE TABLE recipe_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_collection_name UNIQUE (user_id, name)
);

CREATE INDEX idx_collections_user ON recipe_collections(user_id);

-- 5. Collection to Recipe join table supporting many-to-many assignment
CREATE TABLE collection_recipes (
    collection_id BIGINT NOT NULL REFERENCES recipe_collections(id) ON DELETE CASCADE,
    recipe_id VARCHAR(100) NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (collection_id, recipe_id)
);

-- 6. Interactive Cooking Sessions (Distraction-free step tracking, timers & double-deduction prevention)
CREATE TABLE cooking_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipe_id VARCHAR(100) NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    servings INT NOT NULL DEFAULT 2,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    current_step INT NOT NULL DEFAULT 1,
    pantry_deducted BOOLEAN NOT NULL DEFAULT FALSE,
    diary_logged BOOLEAN NOT NULL DEFAULT FALSE,
    notes TEXT
);

CREATE INDEX idx_cooking_sessions_user ON cooking_sessions(user_id);

-- 7. In-App Notifications (Scheduled expiry warnings, meal plan reminders)
CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(50) NOT NULL DEFAULT 'INFO',
    read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_user ON user_notifications(user_id);
